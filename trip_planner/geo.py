"""Shared geo helper — split out so recommender.py and flights.py can both
depend on it without depending on each other (flights.py needs recommender's
data shapes; recommender.py needs flights.py's travel-cost logic to keep the
budget estimate consistent with the "Getting there" options shown to users).
"""

from math import asin, cos, radians, sin, sqrt

EARTH_RADIUS_KM = 6371.0


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    lat1, lon1, lat2, lon2 = map(radians, (lat1, lon1, lat2, lon2))
    dlat, dlon = lat2 - lat1, lon2 - lon1
    a = sin(dlat / 2) ** 2 + cos(lat1) * cos(lat2) * sin(dlon / 2) ** 2
    return 2 * EARTH_RADIUS_KM * asin(sqrt(a))
